
public class Student {
    String name;
    int age;
    double per;

    public Student(String name, int age, double per) {
        this.name = name;
        this.age = age;
        this.per = per;
    }

    public int getAge() { // getter
        return age;
    }

    public void setAge(int AGE) { // setter
        age = AGE;

    }

}